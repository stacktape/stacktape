// Paths are exact, directory prefixes ending /**, or shell-style * globs. They never own new tests implicitly.
export const matchesPath = (pattern: string, path: string): boolean => {
  const subtree = pattern.endsWith('/**');
  const base = subtree ? pattern.slice(0, -3) : pattern;
  const escaped = base.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replaceAll('*', '[^/]*');
  return new RegExp(`^${escaped}${subtree ? '(?:/.*)?' : ''}$`).test(path);
};
export const matchesSlicePath = (slice: Slice, path: string): boolean =>
  slice.tests.includes(path) || slice.paths.some((pattern) => matchesPath(pattern, path));
