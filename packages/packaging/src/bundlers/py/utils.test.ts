import { afterEach, describe, expect, test } from 'bun:test';
import type { PackagingProgressLogger } from '../../runtime-contracts';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildPythonLambda } from '../../buildpacks/py-lambda-buildpack';
import { canInstallRequirementsWithoutSource, getPythonUvDependencySelectorBuildArgs } from './utils';

const createPackagingError = ({ message }: { message: string }) => new Error(message);

const temporaryDirectories: string[] = [];

afterEach(async () => {
  await Promise.all(temporaryDirectories.map((directory) => rm(directory, { force: true, recursive: true })));
  temporaryDirectories.length = 0;
});

const progressLogger: PackagingProgressLogger = {
  eventContext: {},
  startEvent: () => {},
  updateEvent: () => {},
  finishEvent: () => {}
};

describe('Python uv dependency selectors', () => {
  test('rejects selector names that cannot be safely expanded by the Dockerfile shell', () => {
    expect(() =>
      getPythonUvDependencySelectorBuildArgs(
        {
          uvWithGroups: ['prod; rm -rf /']
        },
        createPackagingError
      )
    ).toThrow('Invalid Python uv dependency selector');
  });

  test('rejects selectors on an explicit monorepo requirements file instead of silently ignoring them', async () => {
    const root = await mkdtemp(join(tmpdir(), 'stacktape-python-selectors-'));
    temporaryDirectories.push(root);
    // The explicit file has no default name, so the selector check is only reached if it resolves from cwd.
    await mkdir(join(root, 'services/api/requirements'), { recursive: true });
    await writeFile(join(root, 'services/api/requirements/prod.txt'), 'idna==3.10\n');
    await writeFile(join(root, 'services/api/handler.py'), 'def handler(event, context):\n    return event\n');

    await expect(
      buildPythonLambda({
        name: 'handler',
        cwd: root,
        entryfilePath: 'services/api/handler.py',
        distFolderPath: join(root, 'dist'),
        invocationId: 'test',
        existingDigests: [],
        python: { packageManagerFile: 'services/api/requirements/prod.txt', uvWithGroups: ['prod'] },
        progressLogger,
        createPackagingError,
        runDocker: async () => {
          throw new Error('Docker must not run for a rejected configuration');
        },
        archiveItem: async () => {
          throw new Error('Nothing must be archived for a rejected configuration');
        }
      })
    ).rejects.toThrow('require pyproject.toml or uv.lock');
  });
});

describe('requirements installed before the source', () => {
  const hashed = [
    '# This file was autogenerated by uv via the following command:',
    '#    uv pip compile requirements.in --generate-hashes --output-file requirements.txt',
    'annotated-types==0.8.0 \\',
    '    --hash=sha256:13b2beaad985e05e2d6407ee4c4f35590b11f8d693a258a561055cac8f64cab7 \\',
    '    --hash=sha256:f072f4d804ea359e4eaf198b1af7a8b0943881a87f31bb764f8bf219bb9419e0',
    '    # via pydantic',
    'pydantic[email]==2.11.4 ; python_version >= "3.9" \\',
    '    --hash=sha256:32738d19d63a226a52eed76645a98ee07c1f410ee41d93b4afbfa85ed8111c2d',
    ''
  ].join('\n');

  test.each([
    {
      label: 'pinned requirements',
      contents: 'fastapi==0.115.12\nuvicorn[standard]==0.34.2  # server\n',
      expected: true
    },
    { label: 'hashes continued over lines', contents: hashed, expected: true },
    { label: 'hashes with Windows line endings', contents: hashed.replaceAll('\n', '\r\n'), expected: true },
    { label: 'a version range', contents: 'fastapi>=0.115\n', expected: false },
    { label: 'a nested file', contents: 'fastapi==0.115.12\n-r base.txt\n', expected: false },
    { label: 'the project itself', contents: '-e .\n', expected: false },
    {
      label: 'a continued index option',
      contents: '--index-url \\\n  https://example.com/simple\nidna==3.10\n',
      expected: false
    },
    { label: 'a local path', contents: './vendor/package.whl\n', expected: false }
  ])('$label', async ({ contents, expected }) => {
    const root = await mkdtemp(join(tmpdir(), 'stacktape-python-requirements-'));
    temporaryDirectories.push(root);
    await writeFile(join(root, 'requirements.txt'), contents);
    expect(await canInstallRequirementsWithoutSource(join(root, 'requirements.txt'))).toBe(expected);
  });

  test('a project file beside the requirements, or another file name, needs the source', async () => {
    const root = await mkdtemp(join(tmpdir(), 'stacktape-python-requirements-'));
    temporaryDirectories.push(root);
    await writeFile(join(root, 'requirements-prod.txt'), 'idna==3.10\n');
    expect(await canInstallRequirementsWithoutSource(join(root, 'requirements-prod.txt'))).toBe(false);
    await writeFile(join(root, 'requirements.txt'), 'idna==3.10\n');
    expect(await canInstallRequirementsWithoutSource(join(root, 'requirements.txt'))).toBe(true);
    await writeFile(join(root, 'pyproject.toml'), '[project]\nname = "app"\n');
    expect(await canInstallRequirementsWithoutSource(join(root, 'requirements.txt'))).toBe(false);
  });
});
