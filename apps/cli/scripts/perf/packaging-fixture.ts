/**
 * Deterministic Node Lambda projects for the offline packaging harness.
 *
 * Every byte comes from this file and a fixed seed, so a fixture of a given size is identical on every machine and at
 * every revision until `FIXTURE_GENERATOR_VERSION` changes. Dependencies are vendored as generated packages under
 * `node_modules`, so no package manager or registry is involved. The shape mirrors an ordinary service: handlers share
 * a core library, subsets of handlers share feature modules, one feature reads a binary asset, and handlers use an AWS
 * SDK client that the Lambda runtime provides.
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';

/** Bump whenever generated bytes change, so reports from different generators are never compared by accident. */
export const FIXTURE_GENERATOR_VERSION = 1;

export const FIXTURE_EDITS = ['handler', 'shared', 'manifest', 'asset'] as const;
export type FixtureEdit = (typeof FIXTURE_EDITS)[number];

export type FixtureFunction = { name: string; entryfilePath: string };

export type FixtureManifest = {
  generatorVersion: number;
  functions: FixtureFunction[];
  /** Packages declared in `package.json` and present under `node_modules`. */
  dependencies: Record<string, string>;
  /** Container entrypoint over the same sources, for the opt-in Docker shape. */
  containerEntryfilePath: string;
};

export type FixtureIdentity = { contentSha256: string; files: number; bytes: number };

type Random = () => number;

/** mulberry32: small, fast and fully determined by its seed. */
const createRandom = (seedText: string): Random => {
  let seed = 2166136261;
  for (const character of seedText) {
    seed = Math.imul(seed ^ character.charCodeAt(0), 16777619) >>> 0;
  }
  return () => {
    seed = (seed + 0x6d2b79f5) >>> 0;
    let value = seed;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
};

const NOUNS = `
account address amount archive balance batch billing bucket carrier catalog channel charge checkout coupon
credit currency customer delivery discount dispatch document draft entry estimate event export fulfilment
invoice item journal label ledger line location margin member message notice order parcel payment payout period
plan price product profile quote rate receipt record refund region report request reserve review route schedule
segment session shipment slot source stock store subscription summary supplier tax tenant ticket total transfer
unit usage vendor voucher warehouse window
`
  .trim()
  .split(/\s+/);
const VERBS = `
apply build check collect compose compute derive describe estimate expand filter format group map merge
normalize parse plan prepare rank reconcile reduce render resolve score select sort split summarize validate
`
  .trim()
  .split(/\s+/);

const pick = <T>(random: Random, values: readonly T[]): T => values[Math.floor(random() * values.length)]!;
const capitalize = (word: string) => `${word[0]!.toUpperCase()}${word.slice(1)}`;
const sentence = (random: Random, words: number) => Array.from({ length: words }, () => pick(random, NOUNS)).join(' ');

/** One exported function whose structure varies with the seed, so minification and compression see real variety. */
const generateFunction = (random: Random, name: string, typed: boolean): string => {
  const input = typed ? 'input: Record<string, any>' : 'input';
  const options = typed ? 'options: { mode?: string; limit?: number } = {}' : 'options = {}';
  const [first, second, third] = [pick(random, NOUNS), pick(random, NOUNS), pick(random, NOUNS)];
  const factor = (random() * 9 + 1).toFixed(2);
  const threshold = Math.floor(random() * 5000);
  switch (Math.floor(random() * 4)) {
    case 0:
      return `export function ${name}(${input}, ${options}) {
  const ${first}Items = Array.isArray(input?.${second}) ? input.${second} : [];
  let total = ${threshold};
  for (const item of ${first}Items) {
    if (item && typeof item.${third} === 'number') {
      total += item.${third} * ${factor};
    } else if (typeof item === 'string' && item.startsWith('${pick(random, NOUNS)}')) {
      total -= ${Math.floor(random() * 100)};
    }
  }
  return { kind: '${first}-${second}', total: Math.round(total), limit: options.limit ?? ${Math.floor(random() * 200)} };
}
`;
    case 1:
      return `export function ${name}(${input}, ${options}) {
  switch (options.mode ?? input?.mode) {
    case '${first}':
      return { status: '${second}', value: (input?.${third} ?? 0) + ${threshold}, note: '${sentence(random, 6)}' };
    case '${second}':
      return { status: '${third}', value: Math.max(0, (input?.${first} ?? 0) - ${factor}), note: '${sentence(random, 5)}' };
    case '${third}':
      return { status: '${first}', value: String(input?.${second} ?? '${pick(random, NOUNS)}').length * ${factor} };
    default:
      return { status: 'unknown', value: ${threshold}, note: '${sentence(random, 8)}' };
  }
}
`;
    case 2:
      return `export function ${name}(${input}, ${options}) {
  const parts = [
    '${sentence(random, 3)}',
    String(input?.${first} ?? '${pick(random, NOUNS)}').trim(),
    (input?.${second} ?? []).length > ${Math.floor(random() * 10)} ? '${sentence(random, 4)}' : '${sentence(random, 2)}'
  ];
  const label = parts.filter(Boolean).join(options.mode === '${third}' ? ' / ' : ' - ');
  return { label, key: label.toLowerCase().replaceAll(' ', '-').slice(0, ${Math.floor(random() * 40) + 20}) };
}
`;
    default:
      return `export function ${name}(${input}, ${options}) {
  const entries = Object.entries(input ?? {}).filter(([key]) => !key.startsWith('${first}'));
  const mapped = entries.map(([key, value]) => ({
    key: \`\${key}.${second}\`,
    weight: typeof value === 'number' ? value * ${factor} : ${threshold},
    tags: ['${pick(random, NOUNS)}', '${pick(random, NOUNS)}', options.mode ?? '${third}']
  }));
  return mapped.sort((left, right) => right.weight - left.weight).slice(0, options.limit ?? ${Math.floor(random() * 30) + 5});
}
`;
  }
};

const generateFunctionNames = (random: Random, prefix: string, count: number) =>
  Array.from(
    { length: count },
    (_, index) => `${pick(random, VERBS)}${capitalize(pick(random, NOUNS))}${capitalize(prefix)}${index}`
  );

/** A package whose entry registers every function, so importing it keeps all of it, as most real libraries do. */
const generatePackage = ({
  name,
  version,
  modules,
  functionsPerModule,
  commonJs = false
}: {
  name: string;
  version: string;
  modules: number;
  functionsPerModule: number;
  commonJs?: boolean;
}): Record<string, string> => {
  const random = createRandom(`package:${name}@${version}`);
  const files: Record<string, string> = {};
  const moduleNames = Array.from({ length: modules }, (_, index) => `lib/part-${index}.${commonJs ? 'cjs' : 'js'}`);
  for (const [index, modulePath] of moduleNames.entries()) {
    const names = generateFunctionNames(random, `p${index}`, functionsPerModule);
    const body = names.map((functionName) => generateFunction(random, functionName, false)).join('\n');
    files[modulePath] = commonJs
      ? `'use strict';\n${body.replaceAll('export function ', 'function ')}\nmodule.exports = { ${names.join(', ')} };\n`
      : body;
  }
  files['package.json'] = `${JSON.stringify(
    commonJs
      ? { name, version, main: 'index.cjs', license: 'MIT' }
      : { name, version, type: 'module', main: 'index.js', exports: { '.': './index.js' }, license: 'MIT' },
    null,
    2
  )}\n`;
  files[commonJs ? 'index.cjs' : 'index.js'] = commonJs
    ? `'use strict';
const registry = Object.assign({}, ${moduleNames.map((modulePath) => `require('./${modulePath}')`).join(', ')});
const run = (operation, input, options) => {
  const handler = registry[operation];
  if (!handler) throw new Error('Unknown operation ' + operation);
  return handler(input, options);
};
module.exports = { run, names: Object.keys(registry), version: '${version}' };
`
    : `${moduleNames.map((modulePath, index) => `import * as part${index} from './${modulePath}';`).join('\n')}
const registry = { ${moduleNames.map((_, index) => `...part${index}`).join(', ')} };
export const names = Object.keys(registry);
export const run = (operation, input, options) => {
  const handler = registry[operation];
  if (!handler) throw new Error(\`Unknown operation \${operation}\`);
  return handler(input, options);
};
export default { run, names, version: '${version}' };
`;
  return Object.fromEntries(
    Object.entries(files).map(([path, content]) => [join('node_modules', name, path), content])
  );
};

