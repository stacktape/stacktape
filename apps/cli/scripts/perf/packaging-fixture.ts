const SHARED_REVISION_LINE = "export const SHARED_REVISION = 'fixture-base';";
const HANDLER_REVISION_LINE = "const HANDLER_REVISION = 'fixture-base';";
const ASSET_BYTES = 32 * 1024;

const pad = (value: number) => String(value).padStart(2, '0');
const handlerName = (index: number) => `handler${pad(index)}`;

const generateAsset = (seed: string): Buffer => {
  const random = createRandom(seed);
  return Buffer.from(Array.from({ length: ASSET_BYTES }, () => Math.floor(random() * 256)));
};

/**
 * Generated functions plus a registry that references them. The exported entry uses the registry, so the bundler keeps
 * every function, as it would keep the reachable code of a real module.
 */
const generateSourceModule = ({
  seed,
  prefix,
  functionCount,
  header,
  usage
}: {
  seed: string;
  prefix: string;
  functionCount: number;
  header: string;
  usage: string;
}) => {
  const random = createRandom(seed);
  const names = generateFunctionNames(random, prefix, functionCount);
  return `${header}

${names.map((name) => generateFunction(random, name, true)).join('\n')}
const operations: Record<string, (input: Record<string, any>) => unknown> = { ${names.join(', ')} };

${usage}
`;
};

const generateProjectFiles = (functionCount: number): Record<string, string | Buffer> => {
  const files: Record<string, string | Buffer> = {};
  for (const module of LIBRARY_MODULES) {
    files[`src/lib/${module.file}.ts`] = generateSourceModule({
      seed: `lib:${module.file}`,
      prefix: module.file,
      functionCount: 14,
      header: module.import,
      usage: `export const use${capitalize(module.file)} = (input: Record<string, any>) => ({
  result: ${module.binding}.run(${module.binding}.names[0], input),
  operations: Object.keys(operations)
});`
    });
  }
  files['src/lib/responses.ts'] = generateSourceModule({
    seed: 'lib:responses',
    prefix: 'responses',
    functionCount: 14,
    header: '',
    usage: `${SHARED_REVISION_LINE}
export const jsonResponse = (statusCode: number, body: unknown) => ({
  statusCode,
  headers: { 'content-type': 'application/json', 'x-fixture-revision': SHARED_REVISION },
  body: JSON.stringify({ body, operations: Object.keys(operations) })
});`
  });
  for (const feature of FEATURE_MODULES) {
    const dependencyUse =
      feature.file === 'billing'
        ? 'money.run(money.names[1], input)'
        : feature.file === 'reports'
          ? '{ template: reportTemplatePath, rendered: documents.run(documents.names[2], input) }'
          : `'${feature.file}'`;
    files[`src/features/${feature.file}.ts`] = generateSourceModule({
      seed: `feature:${feature.file}`,
      prefix: feature.file,
      functionCount: 18,
      header: feature.import,
      usage: `export const run${capitalize(feature.file)} = (input: Record<string, any>) => ({
  result: ${dependencyUse},
  operations: Object.keys(operations)
});`
    });
  }
  files['src/assets/report-template.bin'] = generateAsset('asset:report-template');
  files['src/types/assets.d.ts'] = "declare module '*.bin' {\n  const path: string;\n  export default path;\n}\n";

  for (let index = 1; index <= functionCount; index++) {
    // The first handler uses the reports feature, so even a one-function fixture carries the asset and its largest
    // dependency. Every third handler also uses a second feature, so feature modules are shared by different subsets.
    const features = [FEATURE_MODULES[(index + 3) % FEATURE_MODULES.length]!.file];
    if (index % 3 === 0) features.push(FEATURE_MODULES[(index + 1) % FEATURE_MODULES.length]!.file);
    const imports = [
      "import { DynamoDBClient } from '@aws-sdk/client-dynamodb';",
      "import { useLogger } from '../lib/logger';",
      "import { jsonResponse } from '../lib/responses';",
      "import { useIds } from '../lib/ids';",
      "import { useTime } from '../lib/time';",
      "import { useValidation } from '../lib/validation';",
      ...features.map((feature) => `import { run${capitalize(feature)} } from '../features/${feature}';`)
    ].join('\n');
    const usage = `${HANDLER_REVISION_LINE}
const client = new DynamoDBClient({});

export const handler = async (event: { body?: string | null }) => {
  const input = JSON.parse(event.body ?? '{}');
  return jsonResponse(200, {
    handler: '${handlerName(index)}',
    revision: HANDLER_REVISION,
    region: typeof client.config.region === 'string' ? client.config.region : 'runtime',
    logged: useLogger(input),
    id: useIds(input),
    time: useTime(input),
    valid: useValidation(input),
    features: [${features.map((feature) => `run${capitalize(feature)}(input)`).join(', ')}],
    operations: Object.keys(operations)
  });
};`;
    files[`src/handlers/handler-${pad(index)}.ts`] = generateSourceModule({
      seed: `handler:${index}`,
      prefix: `h${index}`,
      functionCount: 5,
      header: imports,
      usage
    });
  }

  files['src/server.ts'] = `import { createServer } from 'node:http';
${FEATURE_MODULES.map((feature) => `import { run${capitalize(feature.file)} } from './features/${feature.file}';`).join('\n')}
import { jsonResponse } from './lib/responses';
import { useValidation } from './lib/validation';

const routes: Record<string, (input: Record<string, any>) => unknown> = {
${FEATURE_MODULES.map((feature) => `  '/${feature.file}': run${capitalize(feature.file)}`).join(',\n')}
};

createServer((request, response) => {
  const route = routes[request.url ?? ''];
  const result = route ? jsonResponse(200, { result: route({}), valid: useValidation({}) }) : jsonResponse(404, {});
  response.writeHead(result.statusCode, result.headers).end(result.body);
}).listen(Number(process.env.PORT ?? 3000));
`;
  return files;
};

const packageJson = (dependencies: Record<string, string>) =>
  `${JSON.stringify(
    {
      name: 'stacktape-packaging-perf-fixture',
      version: '1.0.0',
      private: true,
      type: 'module',
      // The harness keeps fixtures inside the ignored `.stacktape` directory of a Stacktape checkout. Stacktape's
      // project-root discovery stops at the nearest workspace root, which would otherwise be that checkout. An empty
      // workspace list makes the fixture its own root: the same directory a standalone project resolves to.
      workspaces: [],
      dependencies
    },
    null,
    2
  )}\n`;

const packageLock = (dependencies: Record<string, string>) =>
  `${JSON.stringify(
    {
      name: 'stacktape-packaging-perf-fixture',
      version: '1.0.0',
      lockfileVersion: 3,
      requires: true,
      packages: {
        '': { name: 'stacktape-packaging-perf-fixture', version: '1.0.0', dependencies },
        ...Object.fromEntries(
          Object.entries(dependencies).map(([name, version]) => [`node_modules/${name}`, { version, license: 'MIT' }])
        )
      }
    },
    null,
    2
  )}\n`;

const TSCONFIG = `${JSON.stringify(
  {
    compilerOptions: {
      target: 'ES2023',
      module: 'ESNext',
      moduleResolution: 'bundler',
      strict: true,
      skipLibCheck: true,
      noEmit: true
    },
    include: ['src']
  },
  null,
  2
)}\n`;

const dependencyVersions = (packages: VendoredPackage[]) =>
  Object.fromEntries(
    packages.map(({ name, version }) => [name, version]).toSorted(([left], [right]) => (left! < right! ? -1 : 1))
  );

const writeFiles = async (root: string, files: Record<string, string | Buffer>) => {
  for (const [path, content] of Object.entries(files)) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), content);
  }
};

/** Writes a complete fixture project into an empty or absent directory. */
export const writePackagingFixture = async ({
  root,
  functions
}: {
  root: string;
  functions: number;
}): Promise<FixtureManifest> => {
  if (!Number.isInteger(functions) || functions < 1) {
    throw new Error(`A fixture needs at least one function; received ${functions}.`);
  }
  await rm(root, { recursive: true, force: true });
  const dependencies = dependencyVersions(VENDORED_PACKAGES);
  await writeFiles(root, {
    ...generateProjectFiles(functions),
    ...Object.assign({}, ...VENDORED_PACKAGES.map((vendored) => generatePackage(vendored))),
    'package.json': packageJson(dependencies),
    'package-lock.json': packageLock(dependencies),
    'tsconfig.json': TSCONFIG
  });
  return {
    generatorVersion: FIXTURE_GENERATOR_VERSION,
    functions: Array.from({ length: functions }, (_, offset) => ({
      name: handlerName(offset + 1),
      entryfilePath: `src/handlers/handler-${pad(offset + 1)}.ts`
    })),
    dependencies,
    containerEntryfilePath: 'src/server.ts'
  };
};

const replaceOnce = (content: string, search: string, replacement: string, path: string) => {
  if (!content.includes(search)) throw new Error(`Fixture file ${path} does not contain the edit marker.`);
  return content.replace(search, replacement);
};

/**
 * Applies one of the representative edits and returns how to undo it. Every edit is a change a developer makes:
 * one handler's code, the library every handler imports, a newly installed dependency, or a binary asset.
 */
export const applyFixtureEdit = async ({
  root,
  edit
}: {
  root: string;
  edit: FixtureEdit;
}): Promise<{ description: string; revert: () => Promise<void> }> => {
  const originals = new Map<string, Buffer>();
  const created: string[] = [];
  const rewrite = async (path: string, change: (content: Buffer) => string | Buffer) => {
    const absolutePath = join(root, path);
    const original = await readFile(absolutePath);
    originals.set(absolutePath, original);
    await writeFile(absolutePath, change(original));
  };
  let description: string;
  switch (edit) {
    case 'handler':
      description = 'Changed a string constant in src/handlers/handler-01.ts.';
      await rewrite('src/handlers/handler-01.ts', (content) =>
        replaceOnce(
          content.toString(),
          HANDLER_REVISION_LINE,
          HANDLER_REVISION_LINE.replace('base', 'edited'),
          'handler-01'
        )
      );
      break;
    case 'shared':
      description = 'Changed a string constant in src/lib/responses.ts, which every handler imports.';
      await rewrite('src/lib/responses.ts', (content) =>
        replaceOnce(
          content.toString(),
          SHARED_REVISION_LINE,
          SHARED_REVISION_LINE.replace('base', 'edited'),
          'responses'
        )
      );
      break;
    case 'manifest': {
      description = `Installed ${MANIFEST_EDIT_PACKAGE.name}@${MANIFEST_EDIT_PACKAGE.version}: package.json, package-lock.json and node_modules change; no source imports it yet.`;
      const dependencies = dependencyVersions([...VENDORED_PACKAGES, MANIFEST_EDIT_PACKAGE]);
      await rewrite('package.json', () => packageJson(dependencies));
      await rewrite('package-lock.json', () => packageLock(dependencies));
      created.push(join(root, 'node_modules', MANIFEST_EDIT_PACKAGE.name));
      await writeFiles(root, generatePackage(MANIFEST_EDIT_PACKAGE));
      break;
    }
    case 'asset':
      description = 'Replaced the bytes of src/assets/report-template.bin, which one feature module imports.';
      await rewrite('src/assets/report-template.bin', () => generateAsset('asset:report-template:edited'));
      break;
    default:
      throw new Error(`Unknown fixture edit ${edit satisfies never}.`);
  }
  return {
    description,
    revert: async () => {
      for (const [path, content] of originals) await writeFile(path, content);
      for (const path of created) await rm(path, { recursive: true, force: true });
    }
  };
};

/** Edits that change only the Stacktape configuration. Only the full-CLI harness writes and reads that file. */
export const CONFIG_EDITS = ['config'] as const;
export type ConfigEdit = (typeof CONFIG_EDITS)[number];

export const FIXTURE_CONFIG_FILE = 'stacktape.yml';
const CONFIG_REVISION_VALUE = 'fixture-base';

/**
 * Every function packaged with the Stacktape Lambda buildpack. YAML, because a TypeScript configuration imports the
 * `stacktape` package from the project, and the fixture vendors only its own generated packages.
 */
const stacktapeConfig = ({ functions, revision }: { functions: FixtureFunction[]; revision: string }) =>
  [
    '# Generated by the Stacktape CLI measurement harness.',
    'resources:',
    ...functions.flatMap(({ name, entryfilePath }) => [
      `  ${name}:`,
      '    type: function',
      '    properties:',
      '      packaging:',
      '        type: stacktape-lambda-buildpack',
      '        properties:',
      `          entryfilePath: ${entryfilePath}`,
      '      memory: 512',
      '      timeout: 10',
      '      environment:',
      '        - name: CONFIG_REVISION',
      `          value: ${revision}`
    ]),
    ''
  ].join('\n');

/** Writes the configuration the full-CLI harness packages the fixture with. */
export const writeFixtureConfig = async ({ root, functions }: { root: string; functions: FixtureFunction[] }) => {
  await writeFile(join(root, FIXTURE_CONFIG_FILE), stacktapeConfig({ functions, revision: CONFIG_REVISION_VALUE }));
};

/**
 * Changes one function's environment variable value in the configuration and returns how to undo it. No source,
 * manifest or asset changes, so the packages built from it are the same; what changes is deployment configuration.
 */
export const applyConfigEdit = async ({
  root
}: {
  root: string;
}): Promise<{ description: string; revert: () => Promise<void> }> => {
  const path = join(root, FIXTURE_CONFIG_FILE);
  const original = await readFile(path);
  await writeFile(
    path,
    replaceOnce(original.toString(), `value: ${CONFIG_REVISION_VALUE}`, 'value: fixture-edited', FIXTURE_CONFIG_FILE)
  );
  return {
    description: `Changed the value of the first function's CONFIG_REVISION environment variable in ${FIXTURE_CONFIG_FILE}.`,
    revert: async () => {
      await writeFile(path, original);
    }
  };
};

/**
 * Content identity of the fixture's source tree, excluding Stacktape's own `.stacktape` output and any `exclude` path,
 * relative to the root.
 */
export const getFixtureIdentity = async (
  root: string,
  { exclude = [] }: { exclude?: string[] } = {}
): Promise<FixtureIdentity> => {
  const files: string[] = [];
  const walk = async (directory: string) => {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.name === '.stacktape') continue;
      const path = join(directory, entry.name);
      if (exclude.includes(relative(root, path).split('\\').join('/'))) continue;
      if (entry.isDirectory()) await walk(path);
      else files.push(path);
    }
  };
  await walk(root);
  const hash = createHash('sha256');
  let bytes = 0;
  for (const path of files.map((file) => relative(root, file).split('\\').join('/')).toSorted()) {
    const content = await readFile(join(root, path));
    bytes += content.length;
    hash.update(`${path}\0${content.length}\0`);
    hash.update(content);
  }
  return { contentSha256: hash.digest('hex'), files: files.length, bytes };
};
