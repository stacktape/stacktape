  { file: 'validation', binding: 'validation', import: "import validation from '@perf-fixture/validation';" },
  { file: 'time', binding: 'dates', import: "import dates from '@perf-fixture/dates';" },
  { file: 'ids', binding: 'ids', import: "import ids from 'perf-fixture-ids';" }
